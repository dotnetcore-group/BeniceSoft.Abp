-- 仅在 SampleHost 使用的 PostgreSQL 测试库中显式执行，不在应用启动时执行
BEGIN;

CREATE TABLE IF NOT EXISTS sample_transaction_orders
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_id varchar(128) NOT NULL UNIQUE,
    product_code varchar(64) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    amount numeric(18, 2) NOT NULL CHECK (amount >= 0),
    payment_channel varchar(32) NOT NULL,
    state integer NOT NULL CHECK (state BETWEEN 0 AND 5),
    version integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

-- 每个 BizId 独立拥有初始 10 件示例库存，不操作共享商品库存
CREATE TABLE IF NOT EXISTS sample_transaction_inventories
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_id varchar(128) NOT NULL UNIQUE,
    product_code varchar(64) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    available_quantity integer NOT NULL CHECK (available_quantity >= 0),
    frozen_quantity integer NOT NULL CHECK (frozen_quantity >= 0),
    deducted_quantity integer NOT NULL CHECK (deducted_quantity >= 0),
    state integer NOT NULL CHECK (state BETWEEN 0 AND 5),
    version integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CHECK (available_quantity + frozen_quantity + deducted_quantity = 10)
);

COMMIT;
